import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'

async function openParameters(page) {
  await page.goto('/index.html?view=analytical')
  await page.getByRole('button', { name: 'More', exact: false }).click()
  await page.getByRole('button', { name: 'Analytical Models', exact: true }).click()
  await page.getByRole('button', { name: 'Device Parameter Operations', exact: true }).click()
  return page.locator('.parameter-workbench')
}

test('real transfer fit retains exact exported samples, source context and staged Biela application', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  const panel = await openParameters(page)
  await panel.getByLabel('Parameter calculation').selectOption('transfer-fit')
  await panel.locator('[name=source]').fill('Quadratic algebra browser fixture, not a commercial-device measurement')
  await panel.getByRole('button', { name: 'Calculate device parameters', exact: true }).click()
  const result = panel.getByLabel('Device parameter results')
  await expect(result.getByLabel('Exact transfer fit samples')).toBeVisible()
  await expect(result).toContainText('Jacobian rank')
  await expect(result.locator('canvas')).toHaveCount(2)
  const downloaded = page.waitForEvent('download')
  await result.getByRole('button', { name: 'Download reproducible result', exact: true }).click()
  const file = await downloaded
  const exported = JSON.parse(await readFile(await file.path(), 'utf8'))
  expect(exported.result.k_1).toBeCloseTo(2, 8)
  expect(exported.result.k_2).toBeCloseTo(.1, 8)
  expect(exported.result.x).toBeCloseTo(2, 8)
  expect(exported.result.diagnostics.rank).toBe(3)
  expect(exported.result.diagnostics.rmse_a).toBeLessThan(1e-8)
  expect(exported.context.conditions).toEqual({ v_ds_v: 10, t_j_c: 25 })
  expect(exported.plots[0].series.Fitted).toEqual(exported.result.fitted_current_a)
  expect(exported.plots[1].series.Residual).toEqual(exported.result.residual_a)
  await file.saveAs(test.info().outputPath('transfer-extraction.json'))
  await page.screenshot({ path: test.info().outputPath('transfer-fit.png'), fullPage: true })
  await result.getByRole('button', { name: 'Review extracted parameters in Biela', exact: true }).click()
  const biela = page.locator('.biela-calculator')
  await expect(biela.getByLabel('Review extraction application')).toBeVisible()
  await expect(biela.locator('[name=k_1]')).toHaveValue('10')
  await biela.getByRole('button', { name: 'Apply these extracted parameters', exact: true }).click()
  await expect(biela.locator('[name=k_1]')).toHaveValue(String(exported.result.k_1))
  await expect(biela.locator('[name=v_dc]')).toHaveValue('100')
  await expect(biela.locator('[name=q_oss]')).toHaveValue('2e-7')
  await expect(biela.getByLabel('Applied extraction evidence')).toContainText('"v_ds_v": 10')
  await biela.locator('[name=k_1]').fill('3')
  await expect(biela.getByLabel('Applied extraction evidence')).toContainText('Edited manual parameters')
  await page.getByRole('button', { name: 'Device Parameter Operations', exact: true }).click()
  await panel.locator('[name=source]').fill('Source edit invalidates the original fit')
  await expect(result).toHaveCount(0)
  expect(errors).toEqual([])
})

test('real recovery export preserves test conditions and rejects incompatible model Qoss before a deliberate compatible estimate', async ({ page }) => {
  const panel = await openParameters(page)
  await panel.getByLabel('Parameter calculation').selectOption('reverse-recovery-extraction')
  await expect(panel.locator('[name=q_rr_c]')).toHaveValue('100')
  expect(Number(await panel.locator('[name=di_dt_a_s]').inputValue())).toBeCloseTo(2.4, 12)
  await panel.getByRole('button', { name: 'Calculate device parameters', exact: true }).click()
  const result = panel.getByLabel('Device parameter results')
  await expect(result.getByLabel('Recovery readable units')).toContainText('6.7166667')
  const downloaded = page.waitForEvent('download')
  await result.getByRole('button', { name: 'Download reproducible result', exact: true }).click()
  const file = await downloaded
  const exported = JSON.parse(await readFile(await file.path(), 'utf8'))
  expect(exported.result.q_rr_star).toBeCloseTo(88e-9, 15)
  expect(exported.result.tau_c).toBeCloseTo(13.669756359629e-9, 15)
  expect(exported.inputs.q_oss_c).toBe(12e-9)
  expect(exported.inputs.i_forward_test_a).toBe(20)
  expect(exported.inputs.conditions).toEqual({ v_supply_v: 100, t_j_c: 25, q_oss_v_ref_v: 100, q_oss_t_j_c: 25 })
  await file.saveAs(test.info().outputPath('recovery-extraction.json'))
  await result.getByRole('button', { name: 'Review extracted parameters in Biela', exact: true }).click()
  const biela = page.locator('.biela-calculator')
  await biela.getByRole('button', { name: 'Apply these extracted parameters', exact: true }).click()
  await expect(biela.locator('[name=recovery_mode]')).toHaveValue('charge_control')
  await expect(biela.locator('[name=q_oss]')).toHaveValue('2e-7')
  await biela.getByRole('checkbox', { name: 'Use the corrected analytical half-bridge estimate', exact: true }).check()
  await biela.getByRole('button', { name: 'Calculate half-bridge estimate', exact: true }).click()
  await expect(biela.getByRole('alert')).toContainText('Qoss or voltage differs')
  await page.screenshot({ path: test.info().outputPath('recovery-context-conflict.png'), fullPage: true })
  await biela.locator('[name=q_oss]').fill('12e-9')
  await biela.locator('[name=c_gd]').fill('6e-11')
  await biela.locator('[name=c_ds]').fill('6e-11')
  await biela.getByRole('button', { name: 'Calculate half-bridge estimate', exact: true }).click()
  await expect(biela.getByLabel('Biela estimate results')).toBeVisible()
  const estimateDownload = page.waitForEvent('download')
  await biela.getByRole('button', { name: 'Download reproducible estimate JSON', exact: true }).click()
  const estimateFile = await estimateDownload
  const estimate = JSON.parse(await readFile(await estimateFile.path(), 'utf8'))
  expect(estimate.extraction_evidence[0].status).toBe('applied')
  expect(estimate.extraction_evidence[0].inputs).toEqual(exported.inputs)
  expect(estimate.extraction_evidence[0].result).toEqual(exported.result)
  expect(estimate.parameter_inputs_si.q_oss).toBe(12e-9)
  await estimateFile.saveAs(test.info().outputPath('recovery-biela-estimate.json'))
})
