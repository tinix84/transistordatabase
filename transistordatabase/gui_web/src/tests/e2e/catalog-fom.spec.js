test('opens the compiled explorer directly from FastAPI on a narrow screen', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('http://localhost:8002/index.html?view=catalog-fom')
  await expect(page.getByRole('heading', { name: 'FOM & Pareto explorer' })).toBeVisible()
  await expect(page.locator('.summary-cards')).toContainText('174')
  await expect(page.locator('.plot-grid canvas')).toHaveCount(4)
  const charts = await page.locator('.plot-grid canvas').evaluateAll(nodes => nodes.map(n => n.getBoundingClientRect().width))
  expect(charts.every(width => width > 0 && width <= 390), JSON.stringify(charts)).toBe(true)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await page.screenshot({ path: test.info().outputPath('catalog-mobile.png'), fullPage: true })
})
