import { readFile } from 'node:fs/promises'
import { test, expect } from '@playwright/test'

test('overlays physical surveys with independent cost coverage, six panels, and explicit normalization', async ({ page }) => {
  await page.goto('http://localhost:8002/index.html?view=catalog-fom')
  await expect(page.locator('.summary-cards')).toBeVisible()
  await page.getByLabel('Catalog sources', { exact: true }).selectOption(['201210_gan_digikey/CSV', 'SiC_MOSFET_FOM/1200V'])
  await page.getByLabel('X metric', { exact: true }).selectOption('voltage_v')
  await page.getByLabel('Y metric', { exact: true }).selectOption('current_a')
  await expect(page.locator('.fom-workspace .source-note > strong')).toHaveCount(2)
  await expect(page.locator('.cohort-warning')).toContainText('Cost comparison unavailable')
  await expect(page.locator('.scatter-card').nth(2).locator('.scatter-heading')).not.toContainText('0 points')
  await expect(page.locator('.scatter-card').nth(1).locator('.scatter-heading')).toContainText('0 points')
  await page.getByLabel('Survey layout', { exact: true }).selectOption('survey')
  await expect(page.locator('.plot-grid canvas')).toHaveCount(6)
  await page.getByLabel('Axis values', { exact: true }).selectOption('fixed')
  await expect(page.getByText('Normalization population and denominators', { exact: true })).toBeVisible()
  await page.getByLabel('Log X', { exact: true }).first().check()
  const save = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export JSON', exact: true }).click()
  const exported = JSON.parse(await readFile(await (await save).path(), 'utf8'))
  expect(exported.result.sources).toHaveLength(2)
  expect(exported.result.normalization.mode).toBe('fixed')
  const norm = exported.result.normalization.metrics.voltage_v
  expect(norm.denominator).toBeGreaterThan(0)
  expect(norm.denominator_ids.length).toBeGreaterThan(0)
  expect(norm.population_hash).toMatch(/^[a-f0-9]{64}$/)
  expect(exported.result.panels[0].points.length).toBe(exported.result.candidates.filter(p => p.metrics.voltage_v != null && p.metrics.current_a != null).length)
  expect(exported.result.candidates.every(p => p.source.sha256.length === 64)).toBe(true)
  const fixedHash = norm.population_hash
  await page.getByLabel('Min voltage', { exact: true }).fill('650')
  await expect(page.locator('.summary-cards')).toBeVisible()
  const saveFiltered = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export JSON', exact: true }).click()
  const filtered = JSON.parse(await readFile(await (await saveFiltered).path(), 'utf8'))
  expect(filtered.result.normalization.population_hash).toBe(fixedHash)
  await page.getByLabel('Axis values', { exact: true }).selectOption('visible')
  await expect(page.locator('.summary-cards')).toBeVisible()
  const saveVisible = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export JSON', exact: true }).click()
  const visible = JSON.parse(await readFile(await (await saveVisible).path(), 'utf8'))
  expect(visible.result.normalization.mode).toBe('visible')
  expect(visible.result.normalization.population_hash).not.toBe(fixedHash)
})

test('exports the entire catalog without repeating normalization populations on every CSV row', async ({ page }) => {
  await page.goto('http://localhost:8002/index.html?view=catalog-fom')
  await expect(page.locator('.summary-cards')).toBeVisible()
  const ids = await page.getByLabel('Catalog sources', { exact: true }).locator('option').evaluateAll(nodes => nodes.map(node => node.value))
  await page.getByLabel('Catalog sources', { exact: true }).selectOption(ids)
  await page.getByLabel('X metric', { exact: true }).selectOption('voltage_v')
  await page.getByLabel('Y metric', { exact: true }).selectOption('current_a')
  await page.getByLabel('Axis values', { exact: true }).selectOption('fixed')
  await expect(page.locator('.summary-cards').locator('strong').first()).toHaveText('2490')
  const save = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export CSV', exact: true }).click()
  const csv = await readFile(await (await save).path(), 'utf8')
  expect(csv.length).toBeLessThan(15_000_000)
  expect(csv.match(/"full_ids"/g)).toHaveLength(1)
  expect(csv.match(/"hash_reference"/g)).toHaveLength(2489)
  expect(csv).toContain('"source_snapshot_id"')
})

test('screens the real workbook, links plots and exports a reproducible result', async ({ page }) => {
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('/index.html')
  await page.getByRole('button', { name: 'FOM & Pareto', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'FOM & Pareto explorer' })).toBeVisible()
  await expect(page.locator('.summary-cards')).toContainText('Pareto candidates')
  await expect(page.locator('.plot-grid canvas')).toHaveCount(4)
  await page.screenshot({ path: test.info().outputPath('catalog-overview.png'), fullPage: true })
  await page.getByRole('textbox', { name: 'Part or manufacturer', exact: true }).fill('NTHL020N120SC1')
  const part = page.getByRole('button', { name: 'NTHL020N120SC1', exact: true })
  await part.click()
  await expect(page.getByLabel('Selected catalog device')).toContainText('20V')
  await expect(page.getByLabel('Selected catalog device')).toContainText('10000')
  await expect(page.locator('.results-table tbody')).toContainText('2.926e-7')
  await page.getByText('Original cells and cached values', { exact: true }).click()
  await expect(page.locator('.raw-table')).toContainText('=I2/(1200^2/U2)')
  await page.screenshot({ path: test.info().outputPath('catalog-device-detail.png'), fullPage: true })
  await page.getByLabel('Log X', { exact: true }).first().check()
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export JSON', exact: true }).click()
  const download = await downloadPromise
  const saved = JSON.parse(await readFile(await download.path(), 'utf8'))
  expect(saved.request.source_ids).toEqual(['SiC_MOSFET_FOM/1200V'])
  expect(saved.result.points[0].metrics.cost_fom).toBeCloseTo(2.926217777777778e-7, 14)
  expect(saved.result.source.currency).toBe('CHF')
  expect(saved.result.points[0].raw['4'].value).toBe('NTHL020N120SC1')
  const csvPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export CSV', exact: true }).click()
  const csv = await readFile(await (await csvPromise).path(), 'utf8')
  expect(csv).toContain('"currency","snapshot","quote_quantity"')
  expect(csv).toContain('"CHF","historical; date unverified","10000"')
  expect(csv).toContain('"NTHL020N120SC1"')
  const pngPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'PNG', exact: true }).first().click()
  const png = await readFile(await (await pngPromise).path())
  expect([...png.subarray(0, 8)]).toEqual([137, 80, 78, 71, 13, 10, 26, 10])
  await page.getByLabel('Min voltage', { exact: true }).fill('2000')
  await expect(page.locator('.results-table')).toContainText('No candidate rows')
  expect(errors).toEqual([])
})

