import { test, expect } from '@playwright/test'

test('parallel bank displays Python scaling and exports canonical source data', async ({ page }, testInfo) => {
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  await page.goto('/index.html?view=assemblies')
  await expect(page.getByRole('heading', { name: 'Semiconductor assemblies', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Calculate assembly', exact: true }).click()
  const result = page.getByTestId('assembly-results')
  await expect(result).toContainText('30.000000')
  await expect(result).toContainText('0.20000000')
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download assembly JSON' }).click()
  const download = await downloadPromise
  const stream = await download.createReadStream(); let text = ''; for await (const chunk of stream) text += chunk
  const exported = JSON.parse(text)
  expect(exported.device.turn_on.x).toEqual([0, 30])
  expect(exported.device.turn_on.y).toEqual([.00030000000000000003, .003])
  expect(exported.device.shared_sink_resistance_k_per_w).toBe(.2)
  expect(exported.request.device.cost).toBe(2)
  await page.waitForTimeout(1200) // Preserve the completed initial Chart.js animation.
  await page.screenshot({ path: testInfo.outputPath('assembly-desktop.png'), fullPage: true })
  await page.getByLabel('Parallel device count', { exact: true }).fill('4')
  await expect(result).toHaveCount(0)
  expect(errors).toEqual([])
})

