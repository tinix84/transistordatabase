import { expect, test } from '@playwright/test'
import fs from 'node:fs/promises'
import { inspectRenderedChart } from '../fixtures/chartEvidence.js'

async function responseFor(page, route, action) {
  const response = page.waitForResponse(value => value.url().includes(route) && value.request().method() === 'POST')
  await action()
  const received = await response
  expect(received.status()).toBe(200)
  return received.json()
}
async function downloadJson(page, name) {
  const waiting = page.waitForEvent('download')
  await page.getByRole('button', { name, exact: true }).click()
  return JSON.parse(await fs.readFile(await (await waiting).path(), 'utf8'))
}
async function selectOwners(page) {
  await page.getByText('Send exact waveform heat to the thermal workbench', { exact: true }).click()
  for (const direction of ['positive', 'negative', 'zero']) await page.getByLabel(`${direction}-current heat owner`, { exact: true }).selectOption('forward')
  await page.getByLabel('Handoff thermal network', { exact: true }).selectOption('forward')
}
async function assertDrawnValues(plot, expected) {
  const evidence = await plot.evaluate(inspectRenderedChart)
  if (expected) expect(evidence.datasets[0].points.map(point => point.input)).toEqual(expected)
  for (const point of evidence.datasets[0].points) expect(point.value).toBeCloseTo(point.input.y, 7)
}
async function assertCursorPixels(plot, time) {
  const evidence = await plot.evaluate(inspectRenderedChart, time)
  expect(evidence.cursor).toBe(time)
  expect(evidence.drawnTime).toBeCloseTo(time, 12)
  expect(evidence.purplePixels).toBeGreaterThan(20)
}
function withoutHeatOwners(segments) { return segments.map(({ heat_owner, ...segment }) => segment) }

