test('existing waveform workbench sends exact switching event heat into a reviewed thermal network', async ({ page }) => {
  await page.goto('/index.html?view=waveform')
  await page.getByRole('button', { name: 'Load independent switching fixture', exact: true }).click()
  for (const name of ['Positive-current conduction', 'Positive-current turn-on', 'Positive-current turn-off']) await page.getByRole('group', { name, exact: true }).getByLabel('I select this named estimate and its assumptions').check()
  const waveform = await responseFor(page, '/api/waveform/analyze', () => page.getByRole('button', { name: 'Calculate waveform losses', exact: true }).click())
  const stack = page.getByTestId('loss-component-stack')
  await expect(stack.locator('rect[data-component]')).toHaveCount(3)
  for (const [name, value] of Object.entries(waveform.components)) await expect(stack.locator(`rect[data-component=${name}]`)).toHaveAttribute('data-watts', String(value.power_w))
  await stack.evaluate(node => node.scrollIntoView({ block: 'center' }))
  await page.screenshot({ path: test.info().outputPath('waveform-full-component-stack-viewport.png') })
  await selectOwners(page)
  const handoff = await responseFor(page, '/api/analysis/thermal-handoff', () => page.getByRole('button', { name: 'Prepare thermal handoff', exact: true }).click())
  expect(handoff.scope).toBe('complete-waveform-heat')
  expect(handoff.thermal_input.events.map(event => [event.time_s, event.energy_j])).toEqual(waveform.events.map(event => [event.time_s, event.energy_j]))
  await page.getByLabel('I reviewed the thermal source, network, fixed case, initial state and instantaneous event convention.', { exact: true }).check()
  const thermal = await responseFor(page, '/api/thermal/analyze', () => page.getByRole('button', { name: 'Calculate thermal result', exact: true }).click())
  expect(withoutHeatOwners(thermal.request.segments)).toEqual(waveform.power_segments)
  expect(thermal.request.events.map(({ end_s, ...event }) => event)).toEqual(handoff.thermal_input.events)
  expect(thermal.result.switching_energy_j).toBeCloseTo(.003, 14)
})
